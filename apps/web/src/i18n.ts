export type Key = keyof Dict;
const DICT: Record<Lang, Dict> = { ko, ja };
// {min}·{seats}는 설정값 (최소 출발 인원·정원)을 바로 채움
const BASE = { min: SET.MIN_DEPARTURE, seats: SET.BUS_SEATS };
const fill = (s: string, v: Record<string, string | number> = {}) => s.replace(/\{(\w+)\}/g, (_, k) => String(v[k] ?? BASE[k as keyof typeof BASE] ?? ""));

export const useT = () => {
  const L = useApp((s) => s.lang);
  const t = (k: Key, v?: Record<string, string | number>) => fill(DICT[L][k], v);
  const list = (k: Key) => fill(DICT[L][k]).split("|");
  const n = (o: L2) => o[L];
  return { t, list, n, L };
};
// 컴포넌트 밖(토스트 등)에서 쓰는 번역
export const tr = (k: Key, v?: Record<string, string | number>) => fill(DICT[useApp.getState().lang][k], v);
